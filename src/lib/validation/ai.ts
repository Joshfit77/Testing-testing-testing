import { z } from "zod";
import type { ProgramSeed } from "@/data/programs";

/** Shape the model is asked to produce (kept simple for structured outputs). */
export const aiPlanOutputSchema = z.object({
  reply: z.string().describe("A short, friendly explanation of the plan for the user (markdown allowed, no medical claims)."),
  plan: z.object({
    name: z.string(),
    summary: z.string(),
    weeks: z.number().int(),
    session_minutes: z.number().int(),
    difficulty: z.enum(["beginner", "intermediate", "advanced"]),
    progression: z.string(),
    days: z.array(
      z.object({
        name: z.string(),
        focus: z.string(),
        exercises: z.array(
          z.object({
            exercise_slug: z.string(),
            sets: z.number().int(),
            reps: z.string().nullable(),
            seconds: z.number().int().nullable(),
            rest_seconds: z.number().int(),
            rpe: z.number().nullable(),
            notes: z.string().nullable(),
          }),
        ),
      }),
    ),
  }),
});
export type AiPlanOutput = z.infer<typeof aiPlanOutputSchema>;

/** Strict validation applied server-side before anything is shown or saved. */
export const aiPlanStrictSchema = z.object({
  name: z.string().trim().min(2).max(120),
  summary: z.string().trim().min(1).max(300),
  weeks: z.number().int().min(1).max(12),
  session_minutes: z.number().int().min(10).max(150),
  difficulty: z.enum(["beginner", "intermediate", "advanced"]),
  progression: z.string().trim().min(10).max(1500),
  days: z
    .array(
      z.object({
        name: z.string().trim().min(1).max(80),
        focus: z.string().trim().max(120),
        exercises: z
          .array(
            z
              .object({
                exercise_slug: z.string().regex(/^[a-z0-9-]+$/),
                sets: z.number().int().min(1).max(10),
                reps: z
                  .string()
                  .trim()
                  .regex(/^(\d{1,3}(-\d{1,3})?( per side)?|AMRAP)$/i, "reps must look like 8, 8-12, '10 per side' or AMRAP")
                  .nullable(),
                seconds: z.number().int().min(5).max(3600).nullable(),
                rest_seconds: z.number().int().min(0).max(600),
                rpe: z.number().min(4).max(10).nullable(),
                notes: z.string().trim().max(300).nullable(),
              })
              .refine((e) => e.reps || e.seconds, { message: "Each exercise needs reps or seconds" }),
          )
          .min(1)
          .max(10),
      }),
    )
    .min(1)
    .max(7),
});
export type AiPlan = z.infer<typeof aiPlanStrictSchema>;

export type PlanValidation = { ok: true; plan: AiPlan } | { ok: false; errors: string[] };

/** Validate a plan and ensure every exercise exists in the catalog. */
export function validateAiPlan(raw: unknown, knownSlugs: Set<string>): PlanValidation {
  const parsed = aiPlanStrictSchema.safeParse(raw);
  if (!parsed.success) return { ok: false, errors: parsed.error.issues.map((i) => `${i.path.join(".")}: ${i.message}`) };
  const unknown = parsed.data.days.flatMap((d) => d.exercises.map((e) => e.exercise_slug)).filter((s) => !knownSlugs.has(s));
  if (unknown.length) return { ok: false, errors: [`Unknown exercises: ${[...new Set(unknown)].join(", ")}`] };
  return { ok: true, plan: parsed.data };
}

/** Convert a validated AI plan into the program definition format used for saving. */
export function aiPlanToProgramSeed(plan: AiPlan, goals: string[]): ProgramSeed {
  return {
    slug: "ai",
    name: plan.name,
    summary: plan.summary,
    description: `${plan.summary}\n\nGenerated by the AI coach and approved by you. Review exercises and adjust loads to what feels right — skip anything that causes pain.`,
    category: plan.difficulty === "beginner" ? "beginner" : "strength",
    types: [],
    difficulty: plan.difficulty,
    weeks: plan.weeks,
    sessionMinutes: plan.session_minutes,
    goals: goals as ProgramSeed["goals"],
    equipment: [],
    tier: "free",
    progression: plan.progression,
    progressionModel: "linear_rpe",
    deloadFinalWeek: plan.weeks >= 4,
    warmup: ["5 minutes easy cardio", "Dynamic mobility for the joints you'll train", "2–3 progressively heavier warm-up sets of the first lift"],
    cooldown: ["3–5 minutes easy walking", "Gentle stretching for the muscles trained", "Slow breathing for 1–2 minutes"],
    days: plan.days.map((d) => ({
      name: d.name,
      focus: d.focus,
      minutes: plan.session_minutes,
      exercises: d.exercises.map((e) => ({
        ex: e.exercise_slug,
        sets: e.sets,
        reps: e.reps ?? undefined,
        seconds: e.seconds ?? undefined,
        rest: e.rest_seconds,
        rpe: e.rpe ?? undefined,
        notes: e.notes ?? undefined,
      })),
    })),
  };
}
