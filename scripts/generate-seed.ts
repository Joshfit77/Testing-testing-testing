/**
 * Generates supabase/seed.sql from the TypeScript catalog in src/data.
 * Run with: npm run seed:generate
 */
import { createHash } from "node:crypto";
import { writeFileSync } from "node:fs";
import path from "node:path";
import { EXERCISES } from "../src/data/exercises";
import { PROGRAM_CATEGORIES, PROGRAMS } from "../src/data/programs";
import { FEATURE_FLAGS, SEED_CONTENT } from "../src/data/content";
import { COMMON_FOODS } from "../src/data/foods";
import { expandProgram } from "../src/lib/domain/program-expansion";

/** Deterministic UUID derived from a stable key, so re-running the seed is idempotent. */
export function stableUuid(key: string): string {
  const h = createHash("sha1").update(`narrow-gate-fitness:${key}`).digest("hex");
  return `${h.slice(0, 8)}-${h.slice(8, 12)}-5${h.slice(13, 16)}-${((parseInt(h.slice(16, 18), 16) & 0x3f) | 0x80).toString(16)}${h.slice(18, 20)}-${h.slice(20, 32)}`;
}

const q = (v: string | null | undefined) => (v == null ? "null" : `'${v.replace(/'/g, "''")}'`);
const arr = (items: string[]) => (items.length ? `array[${items.map(q).join(", ")}]::text[]` : "'{}'::text[]");
const num = (n: number | null | undefined) => (n == null ? "null" : String(n));
const bool = (b: boolean | undefined) => (b ? "true" : "false");

const lines: string[] = [];
lines.push("-- AUTO-GENERATED by scripts/generate-seed.ts — do not edit by hand.");
lines.push("-- Exercise descriptions are general fitness education, not medical advice.");
lines.push("begin;");
lines.push("");

lines.push("-- Program categories");
PROGRAM_CATEGORIES.forEach((c, i) => {
  lines.push(
    `insert into public.program_categories (id, slug, name, description, sort_order) values (${q(stableUuid(`cat:${c.slug}`))}, ${q(c.slug)}, ${q(c.name)}, ${q(c.description)}, ${i}) on conflict (slug) do update set name = excluded.name, description = excluded.description, sort_order = excluded.sort_order;`,
  );
});
lines.push("");

lines.push("-- Exercises");
for (const e of EXERCISES) {
  lines.push(
    `insert into public.exercises (id, slug, name, primary_muscles, secondary_muscles, equipment, category, movement_pattern, mechanics, difficulty, is_timed, low_impact, description, instructions, form_cues, common_mistakes, is_published) values (` +
      [
        q(stableUuid(`ex:${e.slug}`)),
        q(e.slug),
        q(e.name),
        arr(e.primary),
        arr(e.secondary),
        arr(e.equipment),
        q(e.category),
        q(e.pattern),
        q(e.mechanics ?? null),
        q(e.difficulty),
        bool(e.timed),
        bool(e.lowImpact),
        q(e.description),
        arr(e.instructions),
        arr(e.cues),
        arr(e.mistakes),
        "true",
      ].join(", ") +
      `) on conflict (slug) do update set name = excluded.name, primary_muscles = excluded.primary_muscles, secondary_muscles = excluded.secondary_muscles, equipment = excluded.equipment, category = excluded.category, movement_pattern = excluded.movement_pattern, mechanics = excluded.mechanics, difficulty = excluded.difficulty, is_timed = excluded.is_timed, low_impact = excluded.low_impact, description = excluded.description, instructions = excluded.instructions, form_cues = excluded.form_cues, common_mistakes = excluded.common_mistakes;`,
  );
}
lines.push("");

lines.push("-- Exercise alternatives");
for (const e of EXERCISES) {
  for (const alt of e.alternatives) {
    lines.push(
      `insert into public.exercise_alternatives (exercise_id, alternative_id) values (${q(stableUuid(`ex:${e.slug}`))}, ${q(stableUuid(`ex:${alt}`))}) on conflict do nothing;`,
    );
  }
}
lines.push("");

lines.push("-- Training programs (curated library). Weeks/days/exercises are rebuilt on every seed.");
for (const p of PROGRAMS) {
  const pid = stableUuid(`program:${p.slug}`);
  lines.push(`delete from public.program_weeks where program_id = ${q(pid)};`);
  lines.push(
    `insert into public.training_programs (id, slug, name, summary, description, category_id, difficulty, duration_weeks, days_per_week, session_minutes, goals, equipment, tier, progression, warmup, cooldown, low_impact, is_published, source) values (` +
      [
        q(pid),
        q(p.slug),
        q(p.name),
        q(p.summary),
        q(p.description),
        q(stableUuid(`cat:${p.category}`)),
        q(p.difficulty),
        num(p.weeks),
        num(p.days.length),
        num(p.sessionMinutes),
        arr([...p.goals, ...p.types.map((t) => `type:${t}`)]),
        arr(p.equipment),
        q(p.tier),
        q(p.progression),
        arr(p.warmup),
        arr(p.cooldown),
        bool(p.lowImpact),
        "true",
        q("curated"),
      ].join(", ") +
      `) on conflict (slug) do update set name = excluded.name, summary = excluded.summary, description = excluded.description, category_id = excluded.category_id, difficulty = excluded.difficulty, duration_weeks = excluded.duration_weeks, days_per_week = excluded.days_per_week, session_minutes = excluded.session_minutes, goals = excluded.goals, equipment = excluded.equipment, tier = excluded.tier, progression = excluded.progression, warmup = excluded.warmup, cooldown = excluded.cooldown, low_impact = excluded.low_impact, is_published = true;`,
  );
  for (const week of expandProgram(p)) {
    const wid = stableUuid(`week:${p.slug}:${week.weekNumber}`);
    lines.push(
      `insert into public.program_weeks (id, program_id, week_number, focus, is_deload) values (${q(wid)}, ${q(pid)}, ${week.weekNumber}, ${q(week.focus)}, ${bool(week.isDeload)});`,
    );
    for (const day of week.days) {
      const did = stableUuid(`day:${p.slug}:${week.weekNumber}:${day.dayNumber}`);
      lines.push(
        `insert into public.program_days (id, week_id, day_number, name, focus, estimated_minutes, warmup, cooldown) values (${q(did)}, ${q(wid)}, ${day.dayNumber}, ${q(day.name)}, ${q(day.focus)}, ${num(day.minutes)}, ${arr(day.warmup)}, ${arr(day.cooldown)});`,
      );
      for (const ex of day.exercises) {
        lines.push(
          `insert into public.program_exercises (day_id, exercise_id, position, sets, reps, duration_seconds, rest_seconds, intensity, rpe, notes) values (${q(did)}, ${q(stableUuid(`ex:${ex.ex}`))}, ${ex.position}, ${ex.sets}, ${q(ex.reps ?? null)}, ${num(ex.seconds)}, ${ex.rest}, ${q(ex.intensity ?? null)}, ${num(ex.rpe)}, ${q(ex.notes ?? null)});`,
        );
      }
    }
  }
}
lines.push("");

lines.push("-- Feature flags");
for (const f of FEATURE_FLAGS) {
  lines.push(
    `insert into public.feature_flags (key, enabled, description) values (${q(f.key)}, ${bool(f.enabled)}, ${q(f.description)}) on conflict (key) do update set description = excluded.description;`,
  );
}
lines.push("");

lines.push("-- Public content");
for (const c of SEED_CONTENT) {
  lines.push(
    `insert into public.content_items (id, kind, title, body, scripture_ref, is_published, published_at) values (${q(stableUuid(`content:${c.key}`))}, ${q(c.kind)}, ${q(c.title)}, ${q(c.body)}, ${q(c.scriptureRef ?? null)}, true, now()) on conflict (id) do update set title = excluded.title, body = excluded.body, scripture_ref = excluded.scripture_ref;`,
  );
}
lines.push("");
lines.push("-- Built-in common foods (public, owner_id = null). Typical values, stored as estimates.");
for (const food of COMMON_FOODS) {
  lines.push(
    `insert into public.foods (id, owner_id, name, serving_size, serving_unit, calories, protein_g, carbs_g, fat_g, fiber_g, source, source_ref, is_estimate) values (${q(stableUuid(`food:${food.slug}`))}, null, ${q(food.name)}, ${num(food.servingSize)}, ${q(food.servingUnit)}, ${num(food.calories)}, ${num(food.protein_g)}, ${num(food.carbs_g)}, ${num(food.fat_g)}, ${num(food.fiber_g)}, 'curated', ${q(food.slug)}, true) on conflict (id) do update set name = excluded.name, serving_size = excluded.serving_size, serving_unit = excluded.serving_unit, calories = excluded.calories, protein_g = excluded.protein_g, carbs_g = excluded.carbs_g, fat_g = excluded.fat_g, fiber_g = excluded.fiber_g;`,
  );
}
lines.push("");

lines.push("commit;");

const out = path.resolve(process.cwd(), "supabase/seed.sql");
writeFileSync(out, `${lines.join("\n")}\n`);
console.log(`Wrote ${out} (${EXERCISES.length} exercises, ${PROGRAMS.length} programs, ${PROGRAM_CATEGORIES.length} categories)`);
