/**
 * Writes docs/EXERCISE_DEMOS_2D_STATUS.md: every catalog exercise's 2D demonstration state
 * (src/data/exercise-demo-readiness.json), in launch-priority order (how the programs use it).
 *
 *   npx tsx --tsconfig tsconfig.json scripts/exercise-review/readiness-report.ts
 *
 * Launch priority: tier 1 = in a starter program (beginner, home, active-aging, women's strength) or in 5+ programs;
 * tier 2 = in any other program; tier 3 = in the library only.
 */
import { writeFileSync } from "node:fs";
import { EXERCISES } from "@/data/exercises";
import { PROGRAMS } from "@/data/programs";
import { readinessEntries, READINESS_REVIEW, ownerApproved } from "@/lib/exercise-demo-readiness";

const GROUPS: Record<string, string[]> = {
  starter: ["beginner", "home-workouts", "active-aging", "womens-strength"],
  strength: ["strength", "powerlifting", "powerbuilding", "bench-press", "squat-specialization", "deadlift-specialization", "strongman"],
  bodybuilding: ["hypertrophy", "show-prep"],
  "fat loss / general": ["weight-loss-cardio", "cardiovascular", "functional-conditioning", "hybrid-training", "mobility-flexibility", "recovery-deload", "calisthenics"],
  "MMA / conditioning": ["mma-conditioning", "boxing-conditioning", "grappling-conditioning", "athletic-performance", "speed", "agility"],
};
const groupOf = (category: string) => Object.entries(GROUPS).find(([, cats]) => cats.includes(category))?.[0] ?? "other";

interface DayLike { exercises?: { ex: string }[] }
const usage = new Map<string, { programs: Set<string>; groups: Set<string> }>();
for (const p of PROGRAMS as unknown as Record<string, unknown>[]) {
  const days: DayLike[] = [];
  for (const v of Object.values(p)) {
    if (!Array.isArray(v)) continue;
    for (const item of v as Record<string, unknown>[]) {
      if (item && Array.isArray(item.exercises)) days.push(item as DayLike);
      if (item && Array.isArray(item.days)) days.push(...(item.days as DayLike[]));
    }
  }
  for (const d of days)
    for (const e of d.exercises ?? []) {
      const u = usage.get(e.ex) ?? { programs: new Set(), groups: new Set() };
      u.programs.add(p.slug as string);
      u.groups.add(groupOf(p.category as string));
      usage.set(e.ex, u);
    }
}

const entries = new Map(readinessEntries());
const rows = EXERCISES.map((e) => {
  const u = usage.get(e.slug);
  const n = u?.programs.size ?? 0;
  const tier = u && (u.groups.has("starter") || n >= 5) ? 1 : u ? 2 : 3;
  const r = entries.get(e.slug);
  return { slug: e.slug, name: e.name, tier, n, groups: u ? [...u.groups].sort().join(", ") : "library only", readiness: r?.readiness ?? "placeholder", note: r?.note ?? "", owner: ownerApproved(e.slug) };
}).sort((a, b) => a.tier - b.tier || b.n - a.n || a.name.localeCompare(b.name));

const count = (f: (r: (typeof rows)[number]) => boolean) => rows.filter(f).length;
const states = ["animated", "poses", "placeholder"] as const;
const label = { animated: "Animated", poses: "Pose frames", placeholder: "Placeholder" } as const;

const lines: string[] = [
  "# 2D exercise demonstrations: status",
  "",
  `Generated by \`scripts/exercise-review/readiness-report.ts\` from \`src/data/exercise-demo-readiness.json\` (review ${READINESS_REVIEW.reviewed || "not yet done"}).`,
  "",
  `Method: ${READINESS_REVIEW.method || "—"}`,
  "",
  "**Animated** = the moving 2D athlete is shown (passed the visual review in that look and the automated motion checks). **Pose frames** = still start and mid-rep frames only; the movement between them needs work. **Placeholder** = a labelled \"demonstration in progress\" box; the written steps, cues and mistakes carry the exercise. **Owner approved** is separate and is never set by code.",
  "",
  "| Launch tier | Exercises | Animated | Pose frames | Placeholder | Owner approved |",
  "| --- | --- | --- | --- | --- | --- |",
  ...[1, 2, 3].map((t) => `| ${t === 1 ? "1 (starter programs or 5+ programs)" : t === 2 ? "2 (other programs)" : "3 (library only)"} | ${count((r) => r.tier === t)} | ${states.map((s) => count((r) => r.tier === t && r.readiness === s)).join(" | ")} | ${count((r) => r.tier === t && r.owner)} |`),
  `| **All** | **${rows.length}** | **${states.map((s) => count((r) => r.readiness === s)).join("** | **")}** | **${count((r) => r.owner)}** |`,
  "",
  "## Every exercise",
  "",
  "| Tier | Exercise | Programs | Used in | 2D demo | Owner | Note |",
  "| --- | --- | --- | --- | --- | --- | --- |",
  ...rows.map((r) => `| ${r.tier} | ${r.name} (\`${r.slug}\`) | ${r.n} | ${r.groups} | ${label[r.readiness]} | ${r.owner ? "approved" : "pending"} | ${r.note.replace(/\|/g, "/")} |`),
  "",
];
writeFileSync("docs/EXERCISE_DEMOS_2D_STATUS.md", lines.join("\n"));
console.log(`docs/EXERCISE_DEMOS_2D_STATUS.md: ${rows.length} exercises; ${states.map((s) => `${s} ${count((r) => r.readiness === s)}`).join(", ")}`);
